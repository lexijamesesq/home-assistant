#!/usr/bin/env bash
#
# install-hooks.sh — set up the repository's native hooks on the Pi's checkout.
# Run once from the Terminal & SSH add-on, and again after an add-on update if
# --check reports drift.
#
# The add-on installs pre-commit, Node and npm itself, from its own `apks`
# option. Alpine does not package gitleaks, so this keeps the pinned,
# checksum-verified binary at /config/.tools/gitleaks, then runs the native
# `pre-commit install` that the repository's working guide names, replacing any
# earlier hand-built hooks. pre-commit's environments live under
# /config/.tools/pre-commit, so they survive an add-on update. The scan inputs
# are not installed here: the review host's merged-main apply keeps them current
# under /config/.tools/operator-config. It never edits a Home Assistant
# configuration file.
#
#     tools/install-hooks.sh [--check]
#
# --check reports what is missing and exits non-zero, installing nothing.

set -euo pipefail

MODE=install
[[ "${1:-}" == "--check" ]] && MODE=check

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=tools/pi-hook-env.sh
. "$REPO_ROOT/tools/pi-hook-env.sh"
GITLEAKS_VERSION="8.30.1"
GITLEAKS_ARCHIVE_SHA="e4a487ee7ccd7d3a7f7ec08657610aa3606637dab924210b3aee62570fb4b080"
GITLEAKS_BINARY_SHA="00e91bbe655bd7c47753e8cfe61cb76ea1a5d7e7702fe161ee40102b46b3823b"
TOOLS_DIR="$PI_TOOLS"
GITLEAKS_BIN="$TOOLS_DIR/gitleaks"
GIT_DIR="$(git -C "$REPO_ROOT" rev-parse --absolute-git-dir)"
HOOK_TYPES=(pre-commit pre-push commit-msg prepare-commit-msg)

note() { printf '%s\n' "$1"; }
drift() {
	printf 'DRIFT %s\n' "$1"
	DRIFT=1
}
DRIFT=0

# --- gitleaks, pinned and checksum-verified -----------------------------------
if [[ -x "$GITLEAKS_BIN" ]] &&
	[[ "$(sha256sum "$GITLEAKS_BIN" | cut -d' ' -f1)" == "$GITLEAKS_BINARY_SHA" ]] &&
	[[ "$("$GITLEAKS_BIN" version 2>/dev/null)" == "$GITLEAKS_VERSION" ]]; then
	note "OK    gitleaks $GITLEAKS_VERSION present at $GITLEAKS_BIN"
elif [[ "$MODE" == check ]]; then
	drift "gitleaks $GITLEAKS_VERSION not present at $GITLEAKS_BIN"
else
	mkdir -p "$TOOLS_DIR"
	tmp="$(mktemp -d)"
	trap 'rm -rf "$tmp"' EXIT
	base="https://github.com/gitleaks/gitleaks/releases/download/v${GITLEAKS_VERSION}"
	tarball="gitleaks_${GITLEAKS_VERSION}_linux_arm64.tar.gz"
	curl -sSfL -o "$tmp/$tarball" "$base/$tarball"
	(cd "$tmp" && printf '%s  %s\n' "$GITLEAKS_ARCHIVE_SHA" "$tarball" | sha256sum -c -)
	tar -xzf "$tmp/$tarball" -C "$tmp" gitleaks
	printf '%s  %s\n' "$GITLEAKS_BINARY_SHA" "$tmp/gitleaks" | sha256sum -c -
	install -m 0755 "$tmp/gitleaks" "$GITLEAKS_BIN"
	note "FIXED gitleaks $GITLEAKS_VERSION installed at $GITLEAKS_BIN"
fi

# --- the tools the add-on provides ------------------------------------------
for tool in pre-commit node npm; do
	command -v "$tool" >/dev/null 2>&1 || drift "$tool is missing; add it to the Terminal & SSH add-on's apks option and restart the add-on"
done

# --- the scan inputs the apply keeps current ---------------------------------
for input in gitleaks/operator-rules.toml estate/tag-taxonomy-rosters.md; do
	[[ -r "$XDG_CONFIG_HOME/$input" ]] || drift "$XDG_CONFIG_HOME/$input is missing; the review host's apply delivers it"
done

# --- the native hooks ---------------------------------------------------------
hooks_path_cfg="$(git -C "$REPO_ROOT" config --get core.hooksPath || true)"
[[ -z "$hooks_path_cfg" ]] || drift "core.hooksPath is set to '$hooks_path_cfg'; this script never changes it"
installed=1
for type in "${HOOK_TYPES[@]}"; do
	grep -qs "File generated by pre-commit" "$GIT_DIR/hooks/$type" || installed=0
done
if [[ "$installed" -eq 1 ]]; then
	note "OK    pre-commit hooks installed (${HOOK_TYPES[*]})"
elif [[ "$MODE" == check ]]; then
	drift "pre-commit hooks are not installed for every type (${HOOK_TYPES[*]})"
elif command -v pre-commit >/dev/null 2>&1; then
	(
		cd "$REPO_ROOT"
		pre-commit validate-config .pre-commit-config.yaml
		args=()
		for type in "${HOOK_TYPES[@]}"; do args+=(--hook-type "$type"); done
		pre-commit install --overwrite "${args[@]}"
	)
	rm -f "$GIT_DIR"/hooks/*.legacy
	note "FIXED pre-commit hooks installed (${HOOK_TYPES[*]})"
fi

# --- what the earlier hand-built hooks left behind ---------------------------
if [[ -e "$TOOLS_DIR/dotty-hooks" ]]; then
	if [[ "$MODE" == check ]]; then
		drift "the retired hook bundle is still at $TOOLS_DIR/dotty-hooks"
	else
		rm -rf "$TOOLS_DIR/dotty-hooks"
		note "FIXED removed the retired hook bundle"
	fi
fi

if [[ "$DRIFT" -ne 0 ]]; then
	echo "install-hooks: incomplete — resolve the drift above before committing on the Pi."
	exit 1
fi
echo "install-hooks: ready. Source tools/pi-hook-env.sh before committing on the Pi."
